"""Language, non-destructive data display, studio, and whole-month layout."""
from test_workspace import BASE, OUT
from playwright.sync_api import sync_playwright, expect
from datetime import date, timedelta
import json

with sync_playwright() as pw:
    browser=pw.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE)
    page.wait_for_load_state('networkidle')
    page.locator('[data-lang="zh-CN"]').click()
    expect(page.locator('html')).to_have_attribute('lang','zh-CN')
    expect(page.locator('.bar nav')).to_contain_text('设计工作台')
    expect(page.locator('.hero h1')).to_contain_text('让进展有迹可循')
    page.reload()
    expect(page.locator('html')).to_have_attribute('lang','zh-CN')
    page.locator('.bar nav [href="#studio"]').click()
    expect(page.locator('.research-board')).to_contain_text('研究总览')
    page.screenshot(path=str(OUT/'studio-zh-empty.png'),full_page=True)
    page.locator('[data-action="new-project"]').first.click()
    modal=page.locator('#modal')
    expect(modal).to_contain_text('项目标题')
    expect(modal).to_contain_text('调研论文')
    expect(modal).to_contain_text('终稿写作')
    modal.locator('[name=title]').fill('Read')  # Must not translate user text.
    modal.locator('[name=goal]').fill('中文目标 + English notes <script> 不应被改写。')
    modal.locator('[name=start]').fill(date.today().isoformat())
    modal.locator('[name=due]').fill((date.today()+timedelta(days=30)).isoformat())
    modal.locator('[type=submit]').click()
    expect(modal).not_to_be_visible()
    expect(page.locator('.project-summary h1')).to_have_text('Read')
    expect(page.locator('.stage-nav')).to_contain_text('调研论文')
    expect(page.locator('#stage-status option').first).to_have_text('待开始')
    page.locator('#stage-status').select_option('in progress')
    expect(page.locator('#stage-status')).to_have_value('in progress')
    page.locator('.stage-nav a').filter(has_text='设计算法').click()
    page.locator('[data-action="new-version"]').first.click()
    page.locator('#version-form [name=code]').fill('Read = "Save"\n# Preserve literal code')
    page.locator('#version-form [type=submit]').click()
    page.locator('[data-lang="en"]').click()
    expect(page.locator('#version-form [name=code]')).to_have_value('Read = "Save"\n# Preserve literal code')
    expect(page.locator('.project-summary h1')).to_have_text('Read')
    expect(page.locator('.stage-nav')).to_contain_text('Algorithm design')
    page.locator('[data-lang="zh-CN"]').click()
    page.locator('.stage-nav a').filter(has_text='实验验证').click()
    page.locator('[data-action="add-row"]').click()
    page.locator('td input').first.fill('Reading')
    page.locator('td input').first.press('Tab')
    page.locator('[data-lang="en"]').click()
    expect(page.locator('td input').first).to_have_value('Reading')
    page.locator('[data-lang="zh-CN"]').click()
    page.locator('.stage-nav a').filter(has_text='调研论文').click()
    page.locator('[data-action="new-paper"]').click()
    expect(modal).to_contain_text('论文标题')
    expect(modal).to_contain_text('阅读感受')
    expect(modal.locator('[name=status] option[value="Read"]')).to_have_text('已读')
    modal.locator('[name=title]').fill('Reading')
    modal.locator('[name=status]').select_option('Read')
    modal.locator('[name=pdf]').set_input_files({'name':'reading.pdf','mimeType':'application/pdf','buffer':b'%PDF-1.4\ntrailer<</Size 0>>\n%%EOF'})
    modal.locator('[name=feelings]').fill('Read is my own wording. 保留原文。')
    modal.locator('[type=submit]').click()
    expect(modal).not_to_be_visible()
    page.locator('.bar nav [href="#library"]').click()
    page.locator('#reading-filter').select_option('Read')
    expect(page.locator('#reading-filter option[value="Read"]')).to_have_text('已读')
    expect(page.locator('.paper-card h3')).to_have_text('Reading')
    expect(page.locator('.reading')).to_contain_text('Read is my own wording. 保留原文。')
    page.locator('#reading-filter').select_option('To read')
    expect(page.locator('.paper-card')).to_have_count(0)
    page.locator('#reading-filter').select_option('Read')
    expect(page.locator('.paper-card')).to_have_count(1)
    page.locator('.bar nav [href="#studio"]').click()
    page.screenshot(path=str(OUT/'studio-zh.png'),full_page=True)
    page.locator('[data-action="demo"]').click()
    page.locator('.bar nav [href="#studio"]').click()
    page.screenshot(path=str(OUT/'studio-zh-populated.png'),full_page=True)
    page.locator('[data-lang="en"]').click()
    page.screenshot(path=str(OUT/'studio-en-redesign.png'),full_page=True)
    # Capture reference for visual comparison; reference downtime is not an app failure.
    try:
        ref=page.context.new_page()
        ref.goto('https://gabrygao.github.io/ai-safety-index/',wait_until='networkidle',timeout=25000)
        ref.screenshot(path=str(OUT/'reference-ai-safety-index.png'))
        ref.close()
    except Exception: pass

    page.locator('.bar nav [href="#calendar"]').click()
    page.locator('[data-lang="zh-CN"]').click()
    # March 2026 starts Sunday; six full weeks must fit, not just a five-row month.
    for size in [{'width':1440,'height':900},{'width':1366,'height':768},{'width':1280,'height':720},{'width':390,'height':844}]:
        page.set_viewport_size(size)
        # Current test clock month is irrelevant; step backward until March 2026.
        while page.locator('.month-panel .toolbar h2').inner_text()!='2026年3月':
            text=page.locator('.month-panel .toolbar h2').inner_text()
            if text=='2026年3月': break
            page.locator('[data-action="month-prev"]').click()
        expect(page.locator('.day')).to_have_count(42)
        bounds=page.locator('.calendar-grid').bounding_box()
        assert bounds['y']+bounds['height']<=size['height'],(size,bounds)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.screenshot(path=str(OUT/f"calendar-zh-{size['width']}x{size['height']}.png"))
    # All events remain accessible even when many share a deadline.
    page.locator('[data-action="month-today"]').click()
    expect(page.locator('.more-events').first).to_be_visible()
    page.locator('.more-events').first.click()
    expect(page.locator('#modal .agenda-item')).to_have_count(2)
    page.locator('#modal [data-action="close-modal"]').click()
    page.locator('[data-action="day-details"]').first.click()
    expect(page.locator('#modal')).to_contain_text('当日截止事项')
    page.locator('#modal [data-action="close-modal"]').click()
    for route in ['studio','calendar','library','home']:
        page.set_viewport_size({'width':390,'height':844})
        page.goto(BASE+'/#'+route)
        page.wait_for_load_state('networkidle')
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),route
        page.screenshot(path=str(OUT/f'{route}-zh-mobile-v2.png'),full_page=True)
    assert not errors,errors
    browser.close()
    print('PASS: persisted EN/简中 switch, localized forms/tools, original titles/code/results preserved, redesigned studio, 42-day month fits 900/768/720px screens, day dialogs and mobile layouts.')
